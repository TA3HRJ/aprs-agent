#!/usr/bin/env python3
"""Fail if anything this program sends carries a tocall other than APRAGT,
or if a bridge's ack is not a plain alias-to-sender message.

2026-10-18: aprsorg/aprs-deviceid#368 allocated APRAGT to APRS-Agent, "for
all packets generated by APRS-Agent: the message replies, acks, bridged
messages and the beacon". Until then the gateway and the bridges sent as the
generic APRS (which the device list shows as unknown) and the fixed beacon
as AP4GNT, registered to nobody.

Reading the senders for this found the bridges' acks built as

    ALIAS>SENDER,<the question's own path, q-construct included>::SENDER :ackN

- the sender's callsign in the tocall field - and the e-mail bridge's with
the question's tocall as its source. An ack is a message from the alias
that was addressed: ALIAS>APRAGT,TCPIP*::SENDER   :ackN.

What must hold:

  1. config.TOCALL is APRAGT
  2. no packet builder under extensions/ names APRS or AP4GNT as tocall
  3. the gateway's answer parts, its ack and its status go out as APRAGT
  4. the fixed beacon's position and status go out as APRAGT
  5. every bridge builds its ack as {recipient}>{TOCALL},TCPIP*::

Usage:  python tools/check_tocall.py
Exit code 1 on failure.
"""
from __future__ import annotations

import asyncio
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import config  # noqa: E402
import extensions.ai_gateway_ext as aig  # noqa: E402
from extensions.ai_gateway_ext import AIGateway  # noqa: E402
from extensions.fixed_beacon import FixedBeacon  # noqa: E402

aig._RF_TURNAROUND_S = 0.0
aig._PART_GAP_S = 0.0
aig._RETRY_GAPS_S = ()

BRIDGES = ("telegram_ext.py", "whatsapp_ext.py", "bluesky_ext.py",
           "twitter_ext.py", "smtp_ext.py")


def tocall(pkt: str) -> str:
    return pkt.split(">", 1)[1].split(",", 1)[0]


async def main() -> int:
    problems = []
    # 1
    if getattr(config, "TOCALL", None) != "APRAGT":
        problems.append(f"config.TOCALL is {getattr(config, 'TOCALL', None)!r}")

    # 2
    for f in sorted((ROOT / "extensions").glob("*.py")):
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if line.lstrip().startswith("#"):
                continue
            if re.search(r'f"\{[a-z_]+\}>(?:APRS|AP4GNT),', line):
                problems.append(f"{f.name}:{n} sends with a literal tocall")

    # 3
    sent = []

    class Q:
        async def put(self, b: bytes) -> None:
            sent.append(b.decode("utf-8").strip())

    gw = AIGateway({"enabled": True, "callsign": "DMWGPT", "provider": "deepseek",
                    "api_keys": {"deepseek": "stub"}, "extra_sms": 2}, "")
    gw._own_writer = Q()

    async def stub(question, sender="", history=None):
        return "An answer long enough to need two APRS message parts, so the " \
               "second part follows the first one."
    gw._ask_ai = stub
    await gw.handle("TA1ABC-7>APDR16,TCPIP*,qAC,T2X::DMWGPT   :hello there{42")
    gw_tocalls = sorted({tocall(p) for p in sent})
    print(f"  gateway: {len(sent)} packets, tocalls {gw_tocalls}")
    if not sent or gw_tocalls != ["APRAGT"]:
        problems.append(f"gateway sent tocalls {gw_tocalls}")
    if not any(":ack42" in p for p in sent):
        problems.append("gateway sent no ack to check")

    # 4
    bsent = []
    q: asyncio.Queue = asyncio.Queue()
    fb = FixedBeacon({"enabled": True, "ssid": "TA1ABC-5", "lat": "3900.00N",
                      "lon": "03200.00E", "symbol_table": "/", "symbol": "-",
                      "comment": "test", "beacon_interval_mins": 30,
                      "status_text": "a status"})
    fb.set_own_writer(q)
    await fb._send_beacon()
    await fb._send_status()
    while not q.empty():
        bsent.append(q.get_nowait().decode("utf-8").strip())
    b_tocalls = sorted({tocall(p) for p in bsent})
    print(f"  fixed beacon: {len(bsent)} packets, tocalls {b_tocalls}")
    if len(bsent) != 2 or b_tocalls != ["APRAGT"]:
        problems.append(f"fixed beacon sent {bsent}")

    # 5
    for name in BRIDGES:
        src = (ROOT / "extensions" / name).read_text(encoding="utf-8")
        acks = re.findall(r'ack = f"([^"]*)"', src)
        ok = acks and all(a.startswith("{recipient}>{TOCALL},TCPIP*::{sender_full:<9}:ack")
                          for a in acks)
        print(f"  {name}: ack {acks}")
        if not ok:
            problems.append(f"{name}: ack built as {acks}")

    if problems:
        print("\nFAIL")
        for p in problems:
            print("  - " + p)
        return 1
    print("\nall clear")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
